# 과거 매출 기반 피처를 제거한 build_enhanced_features 함수 # 기존 기수님 코드 피처임
def build_enhanced_features(df: pd.DataFrame, holidays_set: set) -> pd.DataFrame:
    df_copy = df.copy()

    df_copy["dow"] = df_copy["영업일자"].dt.weekday
    df_copy["month"] = df_copy["영업일자"].dt.month
    df_copy["day"] = df_copy["영업일자"].dt.day
    df_copy["week"] = df_copy["영업일자"].apply(lambda d: int(d.isocalendar().week))
    df_copy["quarter"] = df_copy["영업일자"].dt.quarter

    df_copy["is_friday"] = (df_copy["dow"] == 4).astype(int)
    df_copy["is_saturday"] = (df_copy["dow"] == 5).astype(int)
    df_copy["is_sunday"] = (df_copy["dow"] == 6).astype(int)
    df_copy["is_weekend"] = df_copy["dow"].isin([5,6]).astype(int)

    df_copy["is_holiday"] = df_copy["영업일자"].isin(holidays_set).astype(int)
    df_copy["is_off"] = ((df_copy["is_weekend"]==1) | (df_copy["is_holiday"]==1)).astype(int)

    df_copy["tomorrow"] = df_copy["영업일자"] + pd.Timedelta(days=1)
    df_copy["yesterday"] = df_copy["영업일자"] - pd.Timedelta(days=1)
    df_copy["is_before_holiday"] = df_copy["tomorrow"].isin(holidays_set).astype(int)
    df_copy["is_after_holiday"] = df_copy["yesterday"].isin(holidays_set).astype(int)

    df_copy["is_month_start"] = (df_copy["day"] <= 3).astype(int)
    df_copy["is_month_end"] = (df_copy["day"] >= 28).astype(int)

    df_copy["is_spring"] = df_copy["month"].isin([4,5,6]).astype(int)
    df_copy["is_summer"] = df_copy["month"].isin([7,8]).astype(int)
    df_copy["is_autumn"] = df_copy["month"].isin([9,10,11]).astype(int)
    df_copy["is_winter"] = df_copy["month"].isin([12,1,2,3]).astype(int)

    df_copy["is_summer_vacation"] = df_copy["month"].isin([7,8]).astype(int)
    df_copy["is_winter_vacation"] = df_copy["month"].isin([12,1,2]).astype(int)

    df_copy[["month_sin", "month_cos"]] = df_copy["month"].apply(lambda m: pd.Series(sine_cosine_encoding(m, 12)))
    df_copy[["dow_sin", "dow_cos"]] = df_copy["dow"].apply(lambda d: pd.Series(sine_cosine_encoding(d, 7)))
    df_copy[["doy_sin", "doy_cos"]] = df_copy["영업일자"].apply(lambda d: pd.Series(sine_cosine_encoding(d.dayofyear, 365)))
    df_copy[["week_sin", "week_cos"]] = df_copy["week"].apply(lambda w: pd.Series(sine_cosine_encoding(w, 52)))
    df_copy[["quarter_sin", "quarter_cos"]] = df_copy["quarter"].apply(lambda q: pd.Series(sine_cosine_encoding(q, 4)))

    return df_copy.drop(columns=["tomorrow", "yesterday"])

