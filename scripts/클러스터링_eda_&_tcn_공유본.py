def run_menu_visualization_eda(train_csv_path: str):
    # 1. 데이터 로드 및 클러스터링 피처 생성
    print("1. 데이터 로드 및 피처 생성...")
    df = pd.read_csv(train_csv_path)
    df['영업일자'] = pd.to_datetime(df['영업일자'])

    if '영업장명_메뉴명' not in df.columns:
        df['영업장명_메뉴명'] = df['영업장명'] + '_' + df['메뉴명']

    menu_stats = df.groupby('영업장명_메뉴명')['매출수량'].agg(['mean', 'std']).fillna(0).reset_index()
    menu_stats.rename(columns={'mean': 'avg_sales', 'std': 'std_sales'}, inplace=True)

    df['요일'] = df['영업일자'].dt.dayofweek
    menu_weekday_sales = df.groupby(['영업장명_메뉴명', '요일'])['매출수량'].mean().unstack().fillna(0).reset_index()
    menu_weekday_sales.columns = ['영업장명_메뉴명'] + [f'weekday_sales_{i}' for i in range(7)]

    df['월'] = df['영업일자'].dt.month
    menu_month_sales = df.groupby(['영업장명_메뉴명', '월'])['매출수량'].mean().unstack().fillna(0).reset_index()
    menu_month_sales.columns = ['영업장명_메뉴명'] + [f'month_sales_{i}' for i in range(1, 13)]

    menu_stats['메뉴명'] = menu_stats['영업장명_메뉴명'].apply(lambda x: x.split('_', 1)[1])
    menu_stats['menu_category'] = menu_stats['메뉴명'].apply(get_menu_category)

    clustering_df = menu_stats.merge(menu_weekday_sales, on='영업장명_메뉴명')
    clustering_df = clustering_df.merge(menu_month_sales, on='영업장명_메뉴명')

    features_for_clustering = clustering_df.drop(columns=['영업장명_메뉴명', '메뉴명', 'menu_category'])
    scaler = MinMaxScaler()
    scaled_features = scaler.fit_transform(features_for_clustering)

    # 2. PCA 및 클러스터링 적용
    print("2. PCA 및 클러스터링 적용...")
    pca = PCA(n_components=2, random_state=42)
    pca_result = pca.fit_transform(scaled_features)
    clustering_df['pca1'] = pca_result[:, 0]
    clustering_df['pca2'] = pca_result[:, 1]

    # 📌 새로 추가된 코드: PCA의 분산 설명량 출력
    print(f"\n--- PCA 분산 설명량 ---")
    print(f"✅ X축 (주성분 1)의 분산 설명량: {pca.explained_variance_ratio_[0]*100:.2f}%")
    print(f"✅ Y축 (주성분 2)의 분산 설명량: {pca.explained_variance_ratio_[1]*100:.2f}%")
    print(f"✅ 두 주성분의 누적 분산 설명량: {pca.explained_variance_ratio_.sum()*100:.2f}%\n")

    # 📌 새로 추가된 코드: 주성분별 피처 가중치 출력
    pca_loadings = pd.DataFrame(pca.components_.T,
                                columns=['PC1', 'PC2'],
                                index=features_for_clustering.columns)
    print("--- 주성분별 피처 가중치 (상위 5개) ---")
    print("\n✅ X축 (주성분 1) 가중치:")
    print(pca_loadings['PC1'].abs().sort_values(ascending=False).head())
    print("\n✅ Y축 (주성분 2) 가중치:")
    print(pca_loadings['PC2'].abs().sort_values(ascending=False).head())

    kmeans = KMeans(n_clusters=8, random_state=42)
    clustering_df['cluster_id'] = kmeans.fit_predict(scaled_features)

    # 3. 시각화
    print("3. 시각화...")
    plt.figure(figsize=(15, 12))

    sns.scatterplot(x='pca1', y='pca2', hue='cluster_id', data=clustering_df, palette='tab10', legend='full', s=100, alpha=0.7)

    for i, row in clustering_df.sample(5).iterrows():
        plt.text(row['pca1'] + 0.02, row['pca2'] + 0.02, row['영업장명_메뉴명'], fontsize=9)

    plt.title('Menu Items Visualization by Sales Tendency (PCA)')
    plt.xlabel(f'Principal Component 1 ({pca.explained_variance_ratio_[0]*100:.1f}%)')
    plt.ylabel(f'Principal Component 2 ({pca.explained_variance_ratio_[1]*100:.1f}%)')
    plt.grid(True)
    plt.show()

    print("✅ 시각화 완료! 유사한 판매 패턴을 가진 메뉴들은 가까이에 위치합니다.")

    print("--- 모든 클러스터에 속한 메뉴들 (샘플) ---")
    for cluster_id in sorted(clustering_df['cluster_id'].unique()):
        cluster_menus = clustering_df[clustering_df['cluster_id'] == cluster_id]
        print(f"\n[클러스터 {cluster_id}] (총 {len(cluster_menus)}개 메뉴)")
        print(cluster_menus[['영업장명_메뉴명', 'menu_category']].head(5))

    target_cluster_id = 0
    print(f"\n--- 클러스터 {target_cluster_id}의 전체 메뉴 ---")
    full_list = clustering_df[clustering_df['cluster_id'] == target_cluster_id][['영업장명_메뉴명', 'menu_category']]
    print(full_list)

