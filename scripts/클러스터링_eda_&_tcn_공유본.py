class TCNBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size, dilation_factor, dropout_rate):
        super(TCNBlock, self).__init__()
        padding = (kernel_size - 1) * dilation_factor
        self.conv1 = nn.Conv1d(in_channels, out_channels, kernel_size, padding=padding, dilation=dilation_factor)
        self.norm1 = nn.InstanceNorm1d(out_channels)
        self.relu1 = nn.ReLU()
        self.dropout1 = nn.Dropout(dropout_rate)
        self.conv2 = nn.Conv1d(out_channels, out_channels, kernel_size, padding=padding, dilation=dilation_factor)
        self.norm2 = nn.InstanceNorm1d(out_channels)
        self.relu2 = nn.ReLU()
        self.dropout2 = nn.Dropout(dropout_rate)

    def forward(self, x):
        res = x
        out = self.conv1(x)
        out = self.norm1(out[:, :, :-self.conv1.padding[0]])
        out = self.relu1(out)
        out = self.dropout1(out)
        out = self.conv2(out)
        out = self.norm2(out[:, :, :-self.conv2.padding[0]])
        out = self.relu2(out)
        out = self.dropout2(out)
        return out + res

class EnhancedTCNModel(nn.Module):
    def __init__(self, in_len, out_len, cal_dim, n_stores, n_categories, n_types, cfg):
        super().__init__()
        self.in_len = in_len
        self.out_len = out_len

        self.store_emb = nn.Embedding(n_stores, 16)
        self.cat_emb = nn.Embedding(n_categories, 16)
        self.type_emb = nn.Embedding(n_types, 16)

        # NOTE: 과거 매출 기반 피처가 제거되었으므로 cal_dim이 더 작아집니다.
        # 이 코드에서는 cal_dim을 그대로 사용하지만, 실제 피처 수에 맞게 조정될 것입니다.
        input_dim = 1 + 16 + 16 + 16 + cal_dim

        self.tcn_block1 = TCNBlock(input_dim, input_dim, kernel_size=3, dilation_factor=1, dropout_rate=0.1)
        self.tcn_block2 = TCNBlock(input_dim, input_dim, kernel_size=3, dilation_factor=2, dropout_rate=0.1)
        self.tcn_block3 = TCNBlock(input_dim, input_dim, kernel_size=3, dilation_factor=4, dropout_rate=0.1)

        self.fc = nn.Sequential(
            nn.Linear(input_dim * in_len, 256),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(256, out_len * 2)
        )

    def forward(self, x, past_cal, fut_cal, store_idx, cat_idx, type_idx):
        store_emb = self.store_emb(store_idx)
        cat_emb = self.cat_emb(cat_idx)
        type_emb = self.type_emb(type_idx)

        # NOTE: 과거 매출 피처가 없으므로 cal_all은 필요하지 않습니다.
        # past_cal과 fut_cal을 그대로 사용합니다.

        x = x.unsqueeze(-1)
        x_in = torch.cat([
            x,
            store_emb.unsqueeze(1).repeat(1, self.in_len, 1),
            cat_emb.unsqueeze(1).repeat(1, self.in_len, 1),
            type_emb.unsqueeze(1).repeat(1, self.in_len, 1),
            past_cal
        ], dim=-1)

        x_in = x_in.transpose(1, 2)
        out = self.tcn_block1(x_in)
        out = self.tcn_block2(out)
        out = self.tcn_block3(out)
        out = out.transpose(1, 2)

        out = out.reshape(out.shape[0], -1)
        out = self.fc(out)

        v_pred, p_logits = out.chunk(2, dim=-1)

        return v_pred, p_logits

