# 5. 메인 실행 블록 (수정: 저장된 모델 불러와 예측)
# ==============================================================================
if __name__ == "__main__":
    cfg = EnhancedNHiTSConfig()
    if cfg.store_weights is None:
        cfg.store_weights = DEFAULT_STORE_WEIGHTS
    if cfg.custom_holidays_list is None:
        cfg.custom_holidays_list = DEFAULT_CUSTOM_HOLIDAYS

    set_seed(cfg.seed)

    print("💾 저장된 모델 불러오는 중...")
    model_path = "./enhanced_tcn_model.pth"
    checkpoint = torch.load(model_path, map_location=cfg.device)

    train_df = pd.read_csv(cfg.train_csv)
    if '영업장명_메뉴명' not in train_df.columns:
        train_df['영업장명_메뉴명'] = train_df['영업장명'] + '_' + train_df['메뉴명']
    ds_meta = EnhancedNHiTSDataset(cfg, train_df)

    cal_dim = ds_meta.cal_feats.shape[1]
    model = EnhancedTCNModel(
        cfg.in_len, cfg.out_len, cal_dim, ds_meta.n_stores,
        ds_meta.n_categories, ds_meta.n_types, cfg
    ).to(cfg.device)

    model.load_state_dict(checkpoint['model_state'])
    print("✅ 모델 로드 완료!")

    print("🔮 Enhanced TCN 예측...")
    test_files = sorted(glob.glob(cfg.test_glob))
    sub_template = pd.read_csv(cfg.submission_template_csv)
    all_preds_df = pd.DataFrame()

    for test_idx, test_file in enumerate(test_files):
        print(f" 📊 {test_file} 처리 중...")
        tdf = pd.read_csv(test_file)
        if '영업장명_메뉴명' not in tdf.columns:
            tdf['영업장명_메뉴명'] = tdf['영업장명'] + '_' + tdf['메뉴명']

        submit_block = predict_one_file(cfg, model, tdf, ds_meta.store2idx, ds_meta.cat2idx, ds_meta.type2idx)
        submit_block.index = [f"TEST_{test_idx:02d}+{k}일" for k in range(1, cfg.out_len+1)]
        all_preds_df = pd.concat([all_preds_df, submit_block], ignore_index=False)

    final_submit = all_preds_df.reset_index(inplace=False).rename(columns={'index': '영업일자'})
    final_submit = final_submit.reindex(columns=sub_template.columns, fill_value=0)

    num_cols = final_submit.columns.drop('영업일자')
    for col in num_cols:
        Q95 = final_submit[col].quantile(0.95)
        final_submit[col] = np.where(
            final_submit[col] > Q95 * 2.0,
            Q95 * 1.5,
            final_submit[col]
        )

    final_submit[num_cols] = np.rint(np.clip(final_submit[num_cols].values, a_min=0, a_max=None)).astype(int)
    final_submit.to_csv(cfg.out_submission_csv, index=False, encoding="utf-8-sig")

    print(f"✅ Enhanced TCN 완료! → {cfg.out_submission_csv}")
    print("🏆 TCN + Enhanced Features 학습 완료")
