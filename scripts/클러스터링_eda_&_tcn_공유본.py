@torch.no_grad()
def predict_one_file(cfg: EnhancedNHiTSConfig, model: EnhancedTCNModel, test_df: pd.DataFrame,
                     store2idx: Dict, cat2idx: Dict, type2idx: Dict) -> pd.DataFrame:
    device = torch.device(cfg.device)
    tdf = test_df.copy()
    tdf[cfg.date_col] = pd.to_datetime(tdf[cfg.date_col])
    tdf[cfg.target_col] = tdf[cfg.target_col].clip(lower=0)

    last_date = tdf[cfg.date_col].max()
    future_dates = [last_date + pd.Timedelta(days=i) for i in range(1, cfg.out_len + 1)]

    df_with_future = tdf.copy()
    future_df = pd.DataFrame({
        cfg.date_col: future_dates,
        cfg.target_col: [0.0] * cfg.out_len
    })

    all_items = tdf[cfg.item_col].unique()
    future_df_full = pd.concat([
        future_df.assign(**{cfg.item_col: item}) for item in all_items
    ], ignore_index=True)

    df_with_future = pd.concat([df_with_future, future_df_full], ignore_index=True)
    df_with_future.sort_values(by=[cfg.item_col, cfg.date_col], inplace=True)

    holidays_set = set(pd.to_datetime(cfg.custom_holidays_list))
    df_all_feats = build_enhanced_features(df_with_future, holidays_set)

    past_cal_list = []
    fut_cal_list = []
    x_list = []

    for item in all_items:
        item_df = df_all_feats[df_all_feats[cfg.item_col] == item].copy()

        item_sales = item_df[cfg.target_col].values
        x_list.append(item_sales[-(cfg.in_len+cfg.out_len) : -cfg.out_len])

        cal_feat_cols = df_all_feats.columns.drop([cfg.date_col, cfg.item_col, cfg.target_col])
        item_cal_feats = item_df[cal_feat_cols].values

        past_cal_list.append(item_cal_feats[-(cfg.in_len+cfg.out_len) : -cfg.out_len, :])

        fut_cal_list.append(item_cal_feats[-cfg.out_len:, :])

    x = np.stack(x_list, axis=0).astype(np.float32)
    past_cal = np.stack(past_cal_list, axis=0).astype(np.float32)
    fut_cal = np.stack(fut_cal_list, axis=0).astype(np.float32)

    if cfg.log1p:
        x = np.log1p(x)

    x = torch.from_numpy(x).float().to(device)
    past_cal_b = torch.from_numpy(past_cal).float().to(device)
    fut_cal_b = torch.from_numpy(fut_cal).float().to(device)

    stores = [parse_store_name(it) for it in all_items]
    menus = [parse_menu_name(it) for it in all_items]

    store_idx = torch.tensor([store2idx.get(s, 0) for s in stores], dtype=torch.long, device=device)
    cat_idx = torch.tensor([cat2idx.get(get_menu_category(m), 0) for m in menus], dtype=torch.long, device=device)
    type_idx = torch.tensor([type2idx.get(get_store_type(s), 0) for s in stores], dtype=torch.long, device=device)

    amp_ctx = torch.autocast(device_type='cuda', dtype=torch.bfloat16) if (
        cfg.use_amp and torch.cuda.is_available()
    ) else torch.cuda.amp.autocast(enabled=False)

    model.eval()
    with amp_ctx:
        v_pred, p_logits = model(x, past_cal_b, fut_cal_b, store_idx, cat_idx, type_idx)
        y_val = torch.expm1(v_pred).clamp_min(0.0)
        y_prob = torch.sigmoid(p_logits)
        y_hat = (y_prob * y_val).clamp_min(0.0).cpu().numpy()

    return pd.DataFrame(y_hat.T, columns=all_items)

